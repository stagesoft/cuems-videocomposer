/** AC1b: HDMI-A-1 plain and driven, HDMI-A-2 written another way and not driven. */
bool ac1bVector(const std::string& secondSection, const std::string& reasonPiece, const std::string& name = "HDMI-A-2") {
    const std::string text = "canvas_layout=custom\n\n[output:HDMI-A-1]\ncanvas_region=0,0,1920,1080\n\n" + secondSection;
    const DeclaredFile file = plainSections(text);
    const DeclaredSection* s = file.find(name);
    TEST_ASSERT(s != nullptr);
    TEST_ASSERT(file.find("HDMI-A-1") && file.find("HDMI-A-1")->plain);
    if (s->plain || s->notPlainBecause.find(reasonPiece) == std::string::npos) {
        std::cerr << "    " << name << ": plain=" << s->plain << " because '" << s->notPlainBecause << "', expected '"
                  << reasonPiece << "'\n";
        return false;
    }
    const CanvasChoice c = choose(text, named({"HDMI-A-1"}));
    TEST_ASSERT_EQ(c.size, (Size{1920, 1080}));
    return true;
}

