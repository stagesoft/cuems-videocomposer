/** Load a display.conf text into a manager the way DRMBackend does (through a file). */
bool loadText(DisplayConfigurationManager& mgr, const std::string& text) {
    char tmpl[] = "/tmp/vc-canvassize-XXXXXX";
    const int fd = ::mkstemp(tmpl);
    if (fd < 0) return false;
    const bool written = ::write(fd, text.data(), text.size()) == static_cast<ssize_t>(text.size());
    ::close(fd);
    const bool loaded = written && mgr.loadFromFile(tmpl);
    ::unlink(tmpl);
    return loaded;
}

struct Out {
    std::string name;
    int width = 1920;
    int height = 1080;
};

/** The regions this videocomposer drives for these connected outputs (generateOutputRegions, as at start). */
std::vector<Driven> drive(const DisplayConfigurationManager& mgr, const std::vector<Out>& outs) {
    std::vector<OutputInfo> infos;
    for (const auto& o : outs) {
        OutputInfo info;
        info.name = o.name;
        info.width = o.width;
        info.height = o.height;
        info.enabled = true;
        infos.push_back(info);
    }
    std::vector<Driven> driven;
    for (const auto& r : mgr.generateOutputRegions(infos)) {
        driven.push_back(Driven{r.name, Rect{r.canvasX, r.canvasY, r.canvasWidth, r.canvasHeight}});
    }
    return driven;
}

std::vector<Out> named(const std::vector<std::string>& names) {
    std::vector<Out> outs;
    for (const auto& n : names) outs.push_back(Out{n});
    return outs;
}

bool customOf(const DisplayConfigurationManager& mgr) { return mgr.getCanvasLayout() == CanvasLayout::CUSTOM; }

/** The allocation, stubbed: records every attempt; fails for the sizes in `failFor`. */
struct Alloc {
    std::vector<Size> failFor;
    std::vector<Size> seen;
    std::function<bool(int, int)> fn() {
        return [this](int w, int h) {
            seen.push_back(Size{w, h});
            for (const auto& f : failFor) {
                if (f == Size{w, h}) return false;
            }
            return true;
        };
    }
};

const int kGpuLimit = 16384;

/** The canvas the renderer would configure for this text and these connected outputs. */
CanvasChoice choose(const std::string& text, const std::vector<Out>& connected, Alloc* alloc = nullptr,
                    int limit = kGpuLimit) {
    DisplayConfigurationManager mgr;
    loadText(mgr, text);
    const DeclaredFile file = plainSections(text);
    Alloc local;
    Alloc& a = alloc ? *alloc : local;
    return canvasToConfigure(customOf(mgr) ? &file : nullptr, drive(mgr, connected), limit, a.fn());
}

bool hasNote(const std::vector<LayoutNote>& notes, const std::string& code, const std::string& piece = "") {
    for (const auto& n : notes) {
        if (n.code == code && (piece.empty() || n.text.find(piece) != std::string::npos)) return true;
    }
    return false;
}

void printNotes(const std::vector<LayoutNote>& notes) {
    for (const auto& n : notes) {
        std::cerr << "    note " << n.code << ": " << n.text << "\n";
    }
}

/** The notes logged at start for this text and these connected outputs (surfaces decided as DRMBackend does). */
std::vector<LayoutNote> notesFor(const std::string& text, const std::vector<Out>& connected) {
    DisplayConfigurationManager mgr;
    loadText(mgr, text);
    const DeclaredFile file = plainSections(text);
    std::vector<ConnectedOutput> conn;
    for (const auto& o : connected) {
        const OutputConfiguration* oc = mgr.getOutputConfig(o.name);
        conn.push_back(ConnectedOutput{o.name, oc != nullptr, oc ? oc->enabled : true});
    }
    const SurfacePlan plan = surfacesToCreate(conn, customOf(mgr));
    std::vector<Out> withSurface;
    for (const auto& o : connected) {
        for (const auto& c : plan.create) {
            if (c == o.name) withSurface.push_back(o);
        }
    }
    return layoutNotes(file, customOf(mgr), drive(mgr, withSurface), plan);
}

