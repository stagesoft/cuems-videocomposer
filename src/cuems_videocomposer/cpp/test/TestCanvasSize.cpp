// ===== AC3: every listed, enabled output driven: today's canvas, for every fixture =====

bool test_CanvasSize_AC3_AllDrivenIsTodaysCanvas() {
    std::vector<std::string> texts;
    for (const auto& f : canvas_fixtures::engineFixtures()) texts.push_back(f.text);
    texts.push_back(kFour);
    texts.push_back("canvas_layout=custom\n[output:HDMI-A-1]\ncanvas_region=0,0,1920,1080\n[output:HDMI-A-2]\n"
                    "canvas_region=1920,0,1920,1080\n  resolution=1920x1080\n");
    bool ok = true;
    int rows = 0;
    for (const auto& text : texts) {
        DisplayConfigurationManager mgr;
        loadText(mgr, text);
        std::vector<Out> outs;
        for (const auto& oc : mgr.getConfiguration().outputs) {
            if (oc.enabled) outs.push_back(Out{oc.name});
        }
        if (outs.empty()) continue;
        ++rows;
        const std::vector<Driven> driven = drive(mgr, outs);
        const DeclaredFile file = plainSections(text);
        Alloc a;
        const CanvasChoice c = canvasToConfigure(customOf(mgr) ? &file : nullptr, driven, kGpuLimit, a.fn());
        if (c.size != boundingBox(regionsOf(driven))) {
            std::cerr << "    canvas " << c.size << ", driven " << boundingBox(regionsOf(driven)) << " for:\n" << text;
            ok = false;
        }
        const auto notes = notesFor(text, outs);
        for (const auto& n : notes) {
            if (n.code == "W1" || n.code == "W6") {  // nothing undriven, nothing unlisted
                std::cerr << "    unexpected " << n.code << ": " << n.text << "\n";
                ok = false;
            }
        }
    }
    TEST_ASSERT(rows >= 25);
    return ok;
}

