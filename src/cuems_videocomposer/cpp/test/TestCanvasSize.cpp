bool test_CanvasSize_AC1_EngineFixturesClassified() {
    bool ok = true;
    for (const auto& f : canvas_fixtures::engineFixtures()) {
        const DeclaredFile file = plainSections(f.text);
        if (file.sections.size() != f.sections.size()) {
            std::cerr << "    " << f.name << ": " << file.sections.size() << " sections, expected " << f.sections.size()
                      << "\n";
            ok = false;
            continue;
        }
        for (const auto& want : f.sections) {
            const DeclaredSection* s = file.find(want.name);
            const std::string expect = want.expect;
            const bool good = s && (expect == "plain" ? s->plain
                                                      : !s->plain && s->notPlainBecause.find(expect) != std::string::npos);
            if (!good) {
                std::cerr << "    " << f.name << " [" << want.name << "]: got "
                          << (s ? (s->plain ? std::string("plain") : "not plain: " + s->notPlainBecause) : "missing")
                          << ", expected " << expect << "\n";
                ok = false;
            }
        }
    }
    return ok;
}

